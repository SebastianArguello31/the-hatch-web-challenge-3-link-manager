-- Crea las tablas ausentes; no modifica la estructura de tablas que ya existen.
-- Cada enlace guarda su puntuación acumulada, sin identificar a quienes votan.
CREATE TABLE IF NOT EXISTS links (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    url TEXT NOT NULL CHECK (url ~* '^https?://'),
    description TEXT NOT NULL DEFAULT '',
    score INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Las etiquetas son únicas y se almacenan en minúsculas, sin espacios exteriores.
CREATE TABLE IF NOT EXISTS tags (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    CHECK (length(trim(name)) > 0),
    CHECK (name = lower(trim(name)))
);

-- Relación de muchos a muchos: un enlace puede tener varias etiquetas y viceversa.
-- La clave compuesta evita repetir una etiqueta en el mismo enlace.
-- CASCADE elimina relaciones dependientes si se borra su registro padre.
CREATE TABLE IF NOT EXISTS link_tags (
    link_id INTEGER NOT NULL REFERENCES links(id) ON DELETE CASCADE,
    tag_id INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    PRIMARY KEY (link_id, tag_id)
);

-- Cada comentario pertenece a un enlace; author es texto libre, no un usuario registrado.
CREATE TABLE IF NOT EXISTS comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id INTEGER NOT NULL REFERENCES links(id) ON DELETE CASCADE,
    author VARCHAR(100) NOT NULL CHECK (length(trim(author)) > 0),
    content TEXT NOT NULL CHECK (length(trim(content)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Aceleran el filtro por etiqueta y la consulta de comentarios de un enlace.
CREATE INDEX IF NOT EXISTS idx_link_tags_tag_id ON link_tags(tag_id);

CREATE INDEX IF NOT EXISTS idx_comments_link_id ON comments(link_id);
